        // Функция формирует одну строку таблицы из переданной строки данных
        function getTR($data, $columnsCount) {
            // Разбиваем строку по символу * и получаем отдельные ячейки
            $cells = explode('*', $data);
            $hasCells = false;

            // Проверяем, есть ли в строке хотя бы одна непустая ячейка
            for($i = 0; $i < count($cells); $i++) {
                if(trim($cells[$i]) !== '') {
                    $hasCells = true;
                    break;
                }
            }

            // Если строка пустая, не выводим её в таблицу
            if(!$hasCells) {
                return '';
            }

            // Начинаем собирать HTML-код строки таблицы
            $row = '<tr>';

            // Создаём столько ячеек, сколько указано в переменной $columnsCount
            for($i = 0; $i < $columnsCount; $i++) {
                $cellText = '';

                // Если ячейка существует, берём её текст и убираем лишние пробелы
                if(isset($cells[$i])) {
                    $cellText = trim($cells[$i]);
                }

                // Добавляем ячейку в строку, htmlspecialchars нужен для безопасного вывода текста
                $row .= '<td>' . htmlspecialchars($cellText) . '</td>';
            }

            // Закрываем строку таблицы и возвращаем готовый HTML-код
            $row .= '</tr>';

            return $row;
        }

        // Функция формирует и выводит одну таблицу целиком
        function outTable($structure, $columnsCount, $tableNumber) {
            echo '<article class="table-card">';
            echo '<h2>Таблица №' . $tableNumber . '</h2>';

            // Если число колонок неправильное, таблицу не выводим
            if($columnsCount <= 0) {
                echo '<div class="message error">Неправильное число колонок</div>';
                echo '</article>';
                return;
            }

            // Если структура пустая, выводим сообщение об ошибке
            if($structure === '') {
                echo '<div class="message warning">В таблице нет строк</div>';
                echo '</article>';
                return;
            }

            // Разбиваем структуру таблицы на строки по символу #
            $rows = explode('#', $structure);

            // Здесь будет накапливаться HTML-код всех строк таблицы
            $tableRows = '';

            // Каждую строку отправляем в функцию getTR() и добавляем к общей таблице
            for($i = 0; $i < count($rows); $i++) {
                $tableRows .= getTR($rows[$i], $columnsCount);
            }

            // Если после обработки нет строк с ячейками, таблицу не выводим
            if($tableRows === '') {
                echo '<div class="message warning">В таблице нет строк с ячейками</div>';
                echo '</article>';
                return;
            }

            // Выводим готовую таблицу на страницу
            echo '<div class="table-wrap">';
            echo '<table class="lab-table">' . $tableRows . '</table>';
            echo '</div>';
            echo '</article>';
        }

        // Показываем на странице, сколько колонок используется в таблицах
        echo '<p class="lead table-intro">Число колонок таблиц: <strong>' . $columnsCount . '</strong></p>';

        // Проходим по всем структурам из массива и выводим каждую таблицу по очереди
        for($i = 0; $i < count($structures); $i++) {
            outTable($structures[$i], $columnsCount, $i + 1);
        }
